// Point the app at your Appwrite server: reads tn.config.json and writes every file that depends on it.
//   node tools/configure.mjs            write the files
//   node tools/configure.mjs --check    fail if a file is out of date (used by tools/release.mjs)
// Files written:
//   web/config.js                         endpoint / project / database used by the browser
//   web/_headers, web/index.html          Content-Security-Policy (Cloudflare-style headers file + <meta> for hosts
//                                         without custom headers, such as GitHub Pages)
//   appwrite/appwrite.config.json, appwrite/functions/*/src/config.js   (through appwrite/build_config.py)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url)), WEB = ROOT + 'web/';
const CHECK = process.argv.includes('--check');
const fail = msg => { console.error('✗ ' + msg); process.exit(1); };
if (!existsSync(ROOT + 'tn.config.json')) fail('tn.config.json introuvable : copie tn.config.example.json en tn.config.json et remplis-le.');
const read = f => readFileSync(f, 'utf8').replace(/\r\n/g, '\n');   // Windows checkouts may have CRLF
const cfg = JSON.parse(readFileSync(ROOT + 'tn.config.json', 'utf8'));
const aw = cfg.appwrite || {};
const EXAMPLE = process.argv.includes('--example');   // tools/export-public.mjs: keep the placeholders of the example
for (const k of ['endpoint', 'projectId', 'databaseId']) if (!aw[k] || (!EXAMPLE && /<|example/.test(aw[k]))) fail(`tn.config.json : appwrite.${k} n'est pas renseigné`);
let origin; try { origin = new URL(aw.endpoint).origin; } catch { fail('tn.config.json : appwrite.endpoint doit être une adresse complète, ex. https://appwrite.example.com/v1'); }
if (!/^https:/.test(origin) && !/^http:\/\/(localhost|127\.0\.0\.1)(:|$)/.test(origin)) fail('appwrite.endpoint doit être en https');
const ws = origin.replace(/^http/, 'ws');

// Third-party hosts: fonts, CDN scripts (pinned with SRI in index.html), image search thumbnails.
const csp = (frame) => [
  "default-src 'self'",
  "script-src 'self' https://cdnjs.cloudflare.com https://cdn.jsdelivr.net",
  "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
  "font-src 'self' https://fonts.gstatic.com",
  `img-src 'self' data: blob: ${origin} https://*.wikimedia.org https://cdn.pixabay.com https://pixabay.com https://*.mm.bing.net https://external-content.duckduckgo.com`,
  `connect-src 'self' data: ${origin} ${ws} https://commons.wikimedia.org https://*.wikimedia.org`,
  "media-src 'self' data: blob:", "worker-src 'self'", "object-src 'none'", "base-uri 'none'", "form-action 'self'",
  ...(frame ? ["frame-ancestors 'none'"] : []),   // not allowed in <meta>
].join('; ');

const out = {};
out['web/config.js'] = `/* config.js — generated by tools/configure.mjs from tn.config.json (do not edit by hand).
   The Appwrite server this app talks to. Public identifiers, not secrets. */
const TN_CONFIG = ${JSON.stringify({ endpoint: aw.endpoint, project: aw.projectId, db: aw.databaseId })};
`;
const headers = read(WEB + '_headers');
out['web/_headers'] = headers.replace(/^  Content-Security-Policy: .*$/m, '  Content-Security-Policy: ' + csp(true));
const index = read(WEB + 'index.html');
const meta = `<meta http-equiv="Content-Security-Policy" content="${csp(false)}">`;
out['web/index.html'] = /<meta http-equiv="Content-Security-Policy"[^>]*>/.test(index)
  ? index.replace(/<meta http-equiv="Content-Security-Policy"[^>]*>/, meta)
  : index.replace('<meta charset="utf-8">', '<meta charset="utf-8">\n' + meta);

const stale = [];
for (const [f, txt] of Object.entries(out)) {
  const cur = existsSync(ROOT + f) ? read(ROOT + f) : '';
  if (cur === txt) continue;
  if (CHECK) stale.push(f); else writeFileSync(ROOT + f, txt);
}
const py = process.platform === 'win32' ? 'python' : 'python3';
if (CHECK) {
  const before = read(ROOT + 'appwrite/appwrite.config.json');
  execSync(`${py} appwrite/build_config.py`, { cwd: ROOT, stdio: 'ignore' });
  if (read(ROOT + 'appwrite/appwrite.config.json') !== before) stale.push('appwrite/appwrite.config.json');
  if (stale.length) fail(`fichiers à régénérer (node tools/configure.mjs) : ${stale.join(', ')}`);
  console.log('✓ configuration à jour (' + origin + ')');
} else {
  console.log(execSync(`${py} appwrite/build_config.py`, { cwd: ROOT, encoding: 'utf8' }).trim());
  console.log(`✓ app configurée pour ${aw.endpoint} (projet ${aw.projectId})`);
}
